import { useState } from 'react';
import api from '../services/api';
import FormattedAIOutput from '../components/FormattedAIOutput';

const Diet = () => {
  const [goal, setGoal] = useState('Weight Loss');
  const [dietType, setDietType] = useState('Vegetarian');
  const [calories, setCalories] = useState('');
  const [plan, setPlan] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState(false);

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError('');
    setLoading(true);

    try {
      const res = await api.post('/diet/generate', {
        goal,
        dietType,
        calories: Number(calories),
      });
      setPlan(res.data.dietPlan);
    } catch (err) {
      setError(err.response?.data?.message || 'Something went wrong');
    } finally {
      setLoading(false);
    }
  };

  const handleCopy = () => {
    if (!plan) return;
    navigator.clipboard.writeText(plan);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div>
      <div className="card">
        <div className="card-header">
          <h2>Diet Plan Generator</h2>
          <p className="card-subtitle">
            Create an optimal daily nutrition roadmap aligned with your calorie and dietary preferences.
          </p>
        </div>

        {error && <p className="error-text">⚠️ {error}</p>}

        <form onSubmit={handleSubmit}>
          <div>
            <label htmlFor="goal">Target Goal</label>
            <input
              id="goal"
              type="text"
              value={goal}
              onChange={(e) => setGoal(e.target.value)}
              placeholder="e.g. Weight Loss, Muscle Definition, Maintenance"
              required
            />
          </div>

          <div className="form-grid-2">
            <div>
              <label htmlFor="dietType">Dietary Style</label>
              <select
                id="dietType"
                value={dietType}
                onChange={(e) => setDietType(e.target.value)}
              >
                <option value="Vegetarian">Vegetarian</option>
                <option value="Non-Vegetarian">Non-Vegetarian</option>
                <option value="Vegan">Vegan</option>
              </select>
            </div>
            <div>
              <label htmlFor="calories">Target Daily Calories (kcal)</label>
              <input
                id="calories"
                type="number"
                value={calories}
                onChange={(e) => setCalories(e.target.value)}
                placeholder="2000"
                required
              />
            </div>
          </div>

          <button type="submit" disabled={loading}>
            {loading ? 'Generating...' : 'Generate Diet Plan'}
          </button>
        </form>
      </div>

      {plan && (
        <div className="card plan-container">
          <div className="plan-header">
            <h3>Your Diet Plan</h3>
            <button
              type="button"
              className="btn-secondary"
              onClick={handleCopy}
            >
              {copied ? '✓ Copied to clipboard' : '📋 Copy Plan'}
            </button>
          </div>
          <FormattedAIOutput content={plan} showRawToggle />
        </div>
      )}

      <p className="safety-note">
        <span>⚠️</span>
        <span>This is general guidance generated by AI, not medical advice. Consult a professional before starting a new diet or exercise program.</span>
      </p>
    </div>
  );
};

export default Diet;
