import { useState } from 'react';
import api from '../services/api';

const Diet = () => {
  const [goal, setGoal] = useState('Weight Loss');
  const [dietType, setDietType] = useState('Vegetarian');
  const [calories, setCalories] = useState('');
  const [plan, setPlan] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError('');
    setLoading(true);

    try {
      const res = await api.post('/diet/generate', {
        goal,
        dietType,
        calories: Number(calories),
      });
      setPlan(res.data.dietPlan);
    } catch (err) {
      setError(err.response?.data?.message || 'Something went wrong');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div>
      <h2>Diet Plan Generator</h2>
      {error && <p className="error-text">{error}</p>}
      <form onSubmit={handleSubmit}>
        <div>
          <label htmlFor="goal">Goal</label>
          <input
            id="goal"
            type="text"
            value={goal}
            onChange={(e) => setGoal(e.target.value)}
            required
          />
        </div>
        <div>
          <label htmlFor="dietType">Diet Type</label>
          <select
            id="dietType"
            value={dietType}
            onChange={(e) => setDietType(e.target.value)}
          >
            <option value="Vegetarian">Vegetarian</option>
            <option value="Non-Vegetarian">Non-Vegetarian</option>
            <option value="Vegan">Vegan</option>
          </select>
        </div>
        <div>
          <label htmlFor="calories">Calories</label>
          <input
            id="calories"
            type="number"
            value={calories}
            onChange={(e) => setCalories(e.target.value)}
            required
          />
        </div>
        <button type="submit" disabled={loading}>
          {loading ? 'Generating...' : 'Generate Diet Plan'}
        </button>
      </form>
      {plan && (
        <div>
          <h3>Your Diet Plan</h3>
          <pre className="ai-plan" style={{ whiteSpace: 'pre-wrap' }}>{plan}</pre>
        </div>
      )}
      <p className="safety-note">
        This is general guidance generated by AI, not medical advice. Consult a professional before starting a new diet or exercise program.
      </p>
    </div>
  );
};

export default Diet;
