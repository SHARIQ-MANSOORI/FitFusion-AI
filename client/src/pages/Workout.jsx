import { useState } from 'react';
import api from '../services/api';

const Workout = () => {
  const [goal, setGoal] = useState('Muscle Gain');
  const [weight, setWeight] = useState('');
  const [height, setHeight] = useState('');
  const [level, setLevel] = useState('Beginner');
  const [plan, setPlan] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');
  const [copied, setCopied] = useState(false);

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError('');
    setLoading(true);

    try {
      const res = await api.post('/workout/generate', {
        goal,
        weight: Number(weight),
        height: Number(height),
        level,
      });
      setPlan(res.data.workoutPlan);
    } catch (err) {
      setError(err.response?.data?.message || 'Something went wrong');
    } finally {
      setLoading(false);
    }
  };

  const handleCopy = () => {
    if (!plan) return;
    navigator.clipboard.writeText(plan);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div>
      <div className="card">
        <div className="card-header">
          <h2>Workout Plan Generator</h2>
          <p className="card-subtitle">
            Configure your personal profile and fitness targets to generate a customized training program.
          </p>
        </div>

        {error && <p className="error-text">⚠️ {error}</p>}

        <form onSubmit={handleSubmit}>
          <div>
            <label htmlFor="goal">Primary Goal</label>
            <input
              id="goal"
              type="text"
              value={goal}
              onChange={(e) => setGoal(e.target.value)}
              placeholder="e.g. Muscle Gain, Fat Loss, Endurance"
              required
            />
          </div>

          <div className="form-grid-2">
            <div>
              <label htmlFor="weight">Weight (kg)</label>
              <input
                id="weight"
                type="number"
                value={weight}
                onChange={(e) => setWeight(e.target.value)}
                placeholder="70"
                required
              />
            </div>
            <div>
              <label htmlFor="height">Height (cm)</label>
              <input
                id="height"
                type="number"
                value={height}
                onChange={(e) => setHeight(e.target.value)}
                placeholder="175"
                required
              />
            </div>
          </div>

          <div>
            <label htmlFor="level">Experience Level</label>
            <select
              id="level"
              value={level}
              onChange={(e) => setLevel(e.target.value)}
            >
              <option value="Beginner">Beginner</option>
              <option value="Intermediate">Intermediate</option>
              <option value="Advanced">Advanced</option>
            </select>
          </div>

          <button type="submit" disabled={loading}>
            {loading ? 'Generating...' : 'Generate Workout Plan'}
          </button>
        </form>
      </div>

      {plan && (
        <div className="card plan-container">
          <div className="plan-header">
            <h3>Your Workout Plan</h3>
            <button
              type="button"
              className="btn-secondary"
              onClick={handleCopy}
            >
              {copied ? '✓ Copied to clipboard' : '📋 Copy Plan'}
            </button>
          </div>
          <pre className="ai-plan" style={{ whiteSpace: 'pre-wrap' }}>{plan}</pre>
        </div>
      )}

      <p className="safety-note">
        <span>⚠️</span>
        <span>This is general guidance generated by AI, not medical advice. Consult a professional before starting a new diet or exercise program.</span>
      </p>
    </div>
  );
};

export default Workout;
