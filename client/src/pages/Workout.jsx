import { useState } from 'react';
import api from '../services/api';

const Workout = () => {
  const [goal, setGoal] = useState('Muscle Gain');
  const [weight, setWeight] = useState('');
  const [height, setHeight] = useState('');
  const [level, setLevel] = useState('Beginner');
  const [plan, setPlan] = useState('');
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState('');

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError('');
    setLoading(true);

    try {
      const res = await api.post('/workout/generate', {
        goal,
        weight: Number(weight),
        height: Number(height),
        level,
      });
      setPlan(res.data.workoutPlan);
    } catch (err) {
      setError(err.response?.data?.message || 'Something went wrong');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div>
      <h2>Workout Plan Generator</h2>
      {error && <p className="error-text">{error}</p>}
      <form onSubmit={handleSubmit}>
        <div>
          <label htmlFor="goal">Goal</label>
          <input
            id="goal"
            type="text"
            value={goal}
            onChange={(e) => setGoal(e.target.value)}
            required
          />
        </div>
        <div>
          <label htmlFor="weight">Weight (kg)</label>
          <input
            id="weight"
            type="number"
            value={weight}
            onChange={(e) => setWeight(e.target.value)}
            required
          />
        </div>
        <div>
          <label htmlFor="height">Height (cm)</label>
          <input
            id="height"
            type="number"
            value={height}
            onChange={(e) => setHeight(e.target.value)}
            required
          />
        </div>
        <div>
          <label htmlFor="level">Level</label>
          <select
            id="level"
            value={level}
            onChange={(e) => setLevel(e.target.value)}
          >
            <option value="Beginner">Beginner</option>
            <option value="Intermediate">Intermediate</option>
            <option value="Advanced">Advanced</option>
          </select>
        </div>
        <button type="submit" disabled={loading}>
          {loading ? 'Generating...' : 'Generate Workout Plan'}
        </button>
      </form>
      {plan && (
        <div>
          <h3>Your Workout Plan</h3>
          <pre className="ai-plan" style={{ whiteSpace: 'pre-wrap' }}>{plan}</pre>
        </div>
      )}
      <p className="safety-note">
        This is general guidance generated by AI, not medical advice. Consult a professional before starting a new diet or exercise program.
      </p>
    </div>
  );
};

export default Workout;
